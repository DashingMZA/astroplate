// Generates the security-header configuration for every deployment target
// from src/config/csp.json — the single source of truth for the policy.
//
// Usage:
//   node scripts/generate-security-headers.mjs           # write all enabled hosts
//   node scripts/generate-security-headers.mjs --check   # exit 1 if any enabled host is out of sync
//   pnpm headers                                        # same as the first form
//
// Which hosts are generated is controlled by the `hosts` object at the top
// of csp.json (all five are enabled today). A host set to false is skipped
// entirely — its file is left exactly as it is, never deleted. Deleting a
// host's file is a manual step for the day that host is dropped.
//
// The `headers` key of vercel.json is fully managed by this script
// (redirects and $schema are preserved); the other files are edited by
// replacing only their managed region and preserving everything else:
//   - public/_headers: everything from the `/*` line to EOF
//   - netlify.toml: everything from the `[[headers]]` line to EOF
//   - config/nginx/nginx.conf: the contiguous `add_header` block
//   - public/.htaccess: the GENERATED block between the BEGIN/END markers
//     (appended at EOF the first time; the file uses CRLF line endings
//     and the generated block matches them)
//
// HSTS is emitted only for the hosts listed in
// `strict_transport_security.hosts`. nginx is deliberately NOT in that
// list: its container listens on port 80 only (no TLS listener), and HSTS
// must only be served over HTTPS — add it at the TLS terminator instead.
//
// The CSP directive order in csp.json is the live policy order; keep it,
// so a re-run is byte-identical when nothing changed.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CSP_CONFIG_PATH = path.join(ROOT, "src", "config", "csp.json");

// Host key -> file, in the order the files are written.
export const HOST_FILES = {
  vercel: "vercel.json",
  worker: "public/_headers",
  netlify: "netlify.toml",
  nginx: "config/nginx/nginx.conf",
  apache: "public/.htaccess",
};

const APACHE_BEGIN =
  "##### Security headers - GENERATED by scripts/generate-security-headers.mjs from src/config/csp.json - BEGIN";
const APACHE_END =
  "##### Security headers - GENERATED by scripts/generate-security-headers.mjs from src/config/csp.json - END";

export function loadConfig(configPath = CSP_CONFIG_PATH) {
  const config = JSON.parse(readFileSync(configPath, "utf8"));
  const knownHosts = Object.keys(HOST_FILES);
  for (const key of Object.keys(config.hosts ?? {})) {
    if (!knownHosts.includes(key)) {
      throw new Error(`csp.json: unknown host "${key}" (known: ${knownHosts.join(", ")})`);
    }
  }
  for (const [name, sources] of Object.entries(config.content_security_policy ?? {})) {
    if (!Array.isArray(sources)) {
      throw new Error(`csp.json: directive "${name}" must be an array of sources`);
    }
  }
  const hstsHosts = config.strict_transport_security?.hosts ?? [];
  for (const host of hstsHosts) {
    if (!knownHosts.includes(host)) {
      throw new Error(`csp.json: unknown HSTS host "${host}"`);
    }
  }
  return config;
}

// Join the directives in csp.json order into the single policy string.
// A directive with no sources is emitted bare (e.g. upgrade-insecure-requests).
export function buildCspString(directives) {
  return Object.entries(directives)
    .map(([name, sources]) =>
      sources.length === 0 ? name : `${name} ${sources.join(" ")}`,
    )
    .join("; ");
}

// Ordered [name, value] pairs for one host. CSP first, then the shared
// headers, then HSTS only when the host is in the HSTS host list.
export function headersForHost(config, host) {
  const headers = [
    ["Content-Security-Policy", buildCspString(config.content_security_policy)],
    ...Object.entries(config.other_headers ?? {}),
  ];
  if ((config.strict_transport_security?.hosts ?? []).includes(host)) {
    headers.push(["Strict-Transport-Security", config.strict_transport_security.value]);
  }
  return headers;
}

function renderVercel(existing, headers) {
  const doc = JSON.parse(existing);
  const entry = {
    source: "/(.*)",
    headers: headers.map(([key, value]) => ({ key, value })),
  };
  const index = (doc.headers ?? []).findIndex((h) => h.source === "/(.*)");
  const next = [...(doc.headers ?? [])];
  if (index === -1) next.push(entry);
  else next[index] = entry;
  doc.headers = next;
  return `${JSON.stringify(doc, null, 2)}\n`;
}

function renderWorkerHeaders(existing, headers) {
  const lines = existing.split("\n");
  const marker = lines.findIndex((line) => line === "/*");
  if (marker === -1) {
    throw new Error("public/_headers: no /* rule block found");
  }
  const head = lines.slice(0, marker);
  const body = ["/*", ...headers.map(([name, value]) => `  ${name}: ${value}`)];
  return [...head, ...body, ""].join("\n");
}

function renderNetlify(existing, headers) {
  const lines = existing.split("\n");
  const marker = lines.findIndex((line) => line === "[[headers]]");
  if (marker === -1) {
    throw new Error("netlify.toml: no [[headers]] section found");
  }
  const head = lines.slice(0, marker);
  const body = [
    "[[headers]]",
    '  for = "/*"',
    "  [headers.values]",
    ...headers.map(([name, value]) => `    ${name} = "${value}"`),
  ];
  return [...head, ...body, ""].join("\n");
}

function renderNginx(existing, headers) {
  const lines = existing.split("\n");
  const first = lines.findIndex((line) => /^\s*add_header\s/.test(line));
  if (first === -1) {
    throw new Error("config/nginx/nginx.conf: no add_header lines found");
  }
  let last = first;
  while (last + 1 < lines.length && /^\s*add_header\s/.test(lines[last + 1])) last++;
  const body = headers.map(
    ([name, value]) => `    add_header ${name} "${value}" always;`,
  );
  return [...lines.slice(0, first), ...body, ...lines.slice(last + 1)].join("\n");
}

function renderApache(existing, headers) {
  const eol = existing.includes("\r\n") ? "\r\n" : "\n";
  const block = [
    APACHE_BEGIN,
    "<IfModule mod_headers.c>",
    ...headers.map(([name, value]) => `  Header always set ${name} "${value}"`),
    "</IfModule>",
    APACHE_END,
  ];
  const beginAt = existing.indexOf(APACHE_BEGIN);
  const endAt = existing.indexOf(APACHE_END);
  if (beginAt !== -1 && endAt !== -1 && endAt > beginAt) {
    const before = existing.slice(0, beginAt);
    const after = existing.slice(endAt + APACHE_END.length);
    return `${before}${block.join(eol)}${after}`;
  }
  // First run: append the block at EOF, keeping the file's line endings.
  const sep = existing === "" ? "" : existing.endsWith(eol) ? "" : eol;
  return `${existing}${sep}${block.join(eol)}${eol}`;
}

export const RENDERERS = {
  vercel: renderVercel,
  worker: renderWorkerHeaders,
  netlify: renderNetlify,
  nginx: renderNginx,
  apache: renderApache,
};

// Compute the new text for every enabled host. Returns [{ host, file, next }].
export function generateAll(config, readFile) {
  return Object.keys(HOST_FILES)
    .filter((host) => config.hosts?.[host])
    .map((host) => ({
      host,
      file: HOST_FILES[host],
      next: RENDERERS[host](readFile(HOST_FILES[host]), headersForHost(config, host)),
    }));
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const config = loadConfig();
  const results = generateAll(config, (file) =>
    readFileSync(path.join(ROOT, file), "utf8"),
  );
  let changed = 0;
  for (const { host, file, next } of results) {
    const fullPath = path.join(ROOT, file);
    const current = readFileSync(fullPath, "utf8");
    if (current === next) {
      console.log(`ok: ${file} (${host})`);
      continue;
    }
    changed++;
    if (check) {
      console.log(`out of sync: ${file} (${host}) — run pnpm headers`);
    } else {
      writeFileSync(fullPath, next, "utf8");
      console.log(`wrote: ${file} (${host})`);
    }
  }
  for (const host of Object.keys(HOST_FILES)) {
    if (!config.hosts?.[host]) console.log(`skipped (disabled in csp.json): ${HOST_FILES[host]} (${host})`);
  }
  if (check && changed > 0) {
    console.error(`${changed} file(s) out of sync with src/config/csp.json`);
    process.exitCode = 1;
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
